# 5. LIST USERS IN DEPARTMENT
@tool
def list_department_users(department_id: int,limit: int = 50,*,runtime: ToolRuntime[DataAgentContext],) -> dict[str, Any]:
    """
    List users belonging to a department.
    The department must belong to the authenticated user's
    organization.
    """

    if limit <= 0:
        raise ValueError(
            "limit must be greater than zero."
        )

    limit = min(limit, 100)

    db = runtime.context.db
    current_user = runtime.context.current_user

    department = db.execute(
        select(Department).where(
            Department.department_id== department_id,
            Department.organization_id== current_user.organization_id
        )
    ).scalar_one_or_none()

    if department is None:
        return {
            "found": False,
            "department": None,
            "match_count": 0,
            "users": [],
        }

    stmt = (
        select(User)
        .where(
            User.organization_id== current_user.organization_id,
            User.department_id == department_id,
            User.role != UserRole.SUPER_ADMIN,
        )
        .order_by(
            User.name.asc(),
            User.user_id.asc(),
        )
        .limit(limit)
    )

    users = (db.execute(stmt).scalars().all())

    return {
        "found": True,
        "department": {
            "department_id": department.department_id,
            "name": department.name,
        },
        "match_count": len(users),
        "users": [
            _get_user_with_relationships(
                db=db,
                user=user,
            )
            for user in users
        ],
    }

